package com.wanderlink.group;

import com.wanderlink.user.User;
import jakarta.persistence.*;

/**
 * Entity representing a community travel group for coordinated trips.
 */
@Entity
@Table(name = "travel_groups")
public class TravelGroup {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "name", nullable = false, length = 150)
    private String name;

    @Column(name = "destination", nullable = false, length = 100)
    private String destination;

    @Column(name = "description", length = 1000)
    private String description;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "created_by", nullable = false)
    private User createdBy;

    @Column(name = "member_count", nullable = false)
    private Integer memberCount = 1;

    public TravelGroup() {}

    public TravelGroup(String name, String destination, String description, User createdBy) {
        this.name = name;
        this.destination = destination;
        this.description = description;
        this.createdBy = createdBy;
        this.memberCount = 1;
    }

    // Getters and Setters
    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDestination() {
        return destination;
    }

    public void setDestination(String destination) {
        this.destination = destination;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public User getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(User createdBy) {
        this.createdBy = createdBy;
    }

    public Integer getMemberCount() {
        return memberCount;
    }

    public void setMemberCount(Integer memberCount) {
        this.memberCount = memberCount;
    }
}
